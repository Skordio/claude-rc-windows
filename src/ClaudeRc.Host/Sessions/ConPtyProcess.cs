using System.ComponentModel;
using System.Runtime.InteropServices;
using Microsoft.Win32.SafeHandles;
using Windows.Win32;
using Windows.Win32.Foundation;
using Windows.Win32.System.Console;
using Windows.Win32.System.JobObjects;
using Windows.Win32.System.Threading;

namespace ClaudeRc.Host.Sessions;

/// <summary>
/// The native part of a session, as proven by the M0 spike (m0-findings 1): a pseudo-console,
/// a Job Object with <c>KILL_ON_JOB_CLOSE</c>, and the process started suspended in that
/// pseudo-console, assigned to the job, then resumed. Owns every handle; thread-safe for
/// <see cref="WriteInput"/>, <see cref="Resize"/>, <see cref="TerminateJob"/> and
/// <see cref="ClosePseudoConsole"/>. Input goes through an <see cref="InputWriter"/>, so no call
/// here ever waits on the console reading its input, and <see cref="TerminateJob"/> takes no lock
/// that anything slow holds.
/// </summary>
internal sealed unsafe class ConPtyProcess : IDisposable
{
    // Not generated by CsWin32 (m0-findings 1).
    private const uint ProcThreadAttributePseudoConsole = 0x00020016;

    private readonly object _lock = new();
    private readonly SafeFileHandle _job;
    private readonly HANDLE _process;
    private readonly InputWriter _input;
    private HPCON _pseudoConsole;
    private bool _disposed;

    private ConPtyProcess(SafeFileHandle job, HANDLE process, int processId, HPCON pseudoConsole, InputWriter input, FileStream output)
    {
        _job = job;
        _process = process;
        ProcessId = processId;
        _pseudoConsole = pseudoConsole;
        _input = input;
        Output = output;
    }

    /// <summary>The started process.</summary>
    public int ProcessId { get; }

    /// <summary>The pseudo-console's output (VT bytes); reads return 0 at EOF, after <see cref="ClosePseudoConsole"/>.</summary>
    public FileStream Output { get; }

    /// <summary>Starts <paramref name="commandLine"/> in a new pseudo-console and job.</summary>
    /// <exception cref="SessionStartException">Any step failed; everything created so far is released.</exception>
    public static ConPtyProcess Start(string applicationName, string commandLine, string workingDirectory,
        string environmentBlock, short columns, short rows, Func<Stream, Stream>? wrapInput = null)
    {
        HANDLE inRead = default, inWrite = default, outRead = default, outWrite = default;
        HPCON pc = default;
        SafeFileHandle? job = null;
        LPPROC_THREAD_ATTRIBUTE_LIST attributes = default;
        var attributesMemory = nint.Zero;
        var attributesInitialized = false;
        var pi = new PROCESS_INFORMATION();
        try
        {
            if (!PInvoke.CreatePipe(&inRead, &inWrite, null, 0))
                throw Fail("CreatePipe");
            if (!PInvoke.CreatePipe(&outRead, &outWrite, null, 0))
                throw Fail("CreatePipe");
            var hr = PInvoke.CreatePseudoConsole(new COORD { X = columns, Y = rows }, inRead, outWrite, 0, &pc);
            if (hr.Failed)
                throw new SessionStartException($"CreatePseudoConsole failed: 0x{hr.Value:X8}");
            // The pseudo-console has its own copies now.
            Close(ref inRead);
            Close(ref outWrite);

            job = PInvoke.CreateJobObject(null, null);
            if (job.IsInvalid)
                throw Fail("CreateJobObject");
            var limits = new JOBOBJECT_EXTENDED_LIMIT_INFORMATION();
            limits.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT.JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
            if (!PInvoke.SetInformationJobObject((HANDLE)job.DangerousGetHandle(), JOBOBJECTINFOCLASS.JobObjectExtendedLimitInformation,
                    &limits, (uint)sizeof(JOBOBJECT_EXTENDED_LIMIT_INFORMATION)))
                throw Fail("SetInformationJobObject");

            nuint size = 0;
            PInvoke.InitializeProcThreadAttributeList(default, 1, 0, &size);
            attributesMemory = Marshal.AllocHGlobal((nint)size);
            attributes = new LPPROC_THREAD_ATTRIBUTE_LIST((void*)attributesMemory);
            if (!PInvoke.InitializeProcThreadAttributeList(attributes, 1, 0, &size))
                throw Fail("InitializeProcThreadAttributeList");
            attributesInitialized = true;
            if (!PInvoke.UpdateProcThreadAttribute(attributes, 0, ProcThreadAttributePseudoConsole, (void*)pc.Value,
                    (nuint)sizeof(HPCON), null, null))
                throw Fail("UpdateProcThreadAttribute");

            var si = new STARTUPINFOEXW();
            si.StartupInfo.cb = (uint)sizeof(STARTUPINFOEXW);
            si.lpAttributeList = attributes;
            // With null std handles: otherwise a host whose own std handles are redirected (tests,
            // Task Scheduler) passes them on and the child writes there instead (m0-findings 1).
            si.StartupInfo.dwFlags = STARTUPINFOW_FLAGS.STARTF_USESTDHANDLES;

            // A child inherits its parent's "ignore Ctrl+C" flag, which a parent started in a new
            // process group (Task Scheduler, test runners) has set: the 0x03 stop (SPEC 6.4) would
            // then never reach claude. Clear it for this process, and so for its children.
            PInvoke.SetConsoleCtrlHandler(null, false);

            var cmd = (commandLine + "\0").ToCharArray();
            fixed (char* pApp = applicationName)
            fixed (char* pCmd = cmd)
            fixed (char* pCwd = workingDirectory)
            fixed (char* pEnv = environmentBlock)
            {
                if (!PInvoke.CreateProcess(new PCWSTR(pApp), new PWSTR(pCmd), null, null, false,
                        PROCESS_CREATION_FLAGS.EXTENDED_STARTUPINFO_PRESENT | PROCESS_CREATION_FLAGS.CREATE_SUSPENDED |
                        PROCESS_CREATION_FLAGS.CREATE_UNICODE_ENVIRONMENT,
                        pEnv, new PCWSTR(pCwd), (STARTUPINFOW*)&si, &pi))
                    throw Fail($"starting {applicationName} in {workingDirectory}");
            }
            if (!PInvoke.AssignProcessToJobObject((HANDLE)job.DangerousGetHandle(), pi.hProcess))
            {
                var error = Fail("AssignProcessToJobObject");
                PInvoke.TerminateProcess(pi.hProcess, 1);
                throw error;
            }
            PInvoke.ResumeThread(pi.hThread);
            Close(ref pi.hThread);

            Stream inputStream = new FileStream(new SafeFileHandle((nint)inWrite.Value, ownsHandle: true), FileAccess.Write, 1);
            inWrite = default;
            if (wrapInput is not null)
                inputStream = wrapInput(inputStream);
            var input = new InputWriter(inputStream, $"session {pi.dwProcessId}");
            var output = new FileStream(new SafeFileHandle((nint)outRead.Value, ownsHandle: true), FileAccess.Read, 1);
            outRead = default;
            var started = new ConPtyProcess(job, pi.hProcess, (int)pi.dwProcessId, pc, input, output);
            job = null;
            pc = default;
            pi.hProcess = default;
            return started;
        }
        finally
        {
            if (attributesMemory != nint.Zero)
            {
                if (attributesInitialized)
                    PInvoke.DeleteProcThreadAttributeList(attributes);
                Marshal.FreeHGlobal(attributesMemory);
            }
            Close(ref pi.hThread);
            Close(ref pi.hProcess);
            job?.Dispose(); // kills the process if it got into the job
            if (pc.Value != 0)
                PInvoke.ClosePseudoConsole(pc);
            Close(ref inRead);
            Close(ref inWrite);
            Close(ref outRead);
            Close(ref outWrite);
        }
    }

    private static SessionStartException Fail(string what)
    {
        var error = Marshal.GetLastPInvokeError();
        return new SessionStartException($"{what} failed: {new Win32Exception(error).Message} ({error})");
    }

    private static void Close(ref HANDLE handle)
    {
        if (handle.Value != null && (nint)handle.Value != -1)
            PInvoke.CloseHandle(handle);
        handle = default;
    }

    /// <summary>Blocks until the process exits and returns its exit code.</summary>
    public int WaitForExit()
    {
        PInvoke.WaitForSingleObject(_process, uint.MaxValue); // INFINITE
        uint code;
        PInvoke.GetExitCodeProcess(_process, &code);
        return unchecked((int)code);
    }

    /// <summary>
    /// Queues bytes for the pseudo-console's input and returns at once; false when it is gone or
    /// not reading (its queue is full).
    /// </summary>
    public bool WriteInput(ReadOnlySpan<byte> bytes) => _input.TryWrite(bytes);

    /// <summary>Resizes the pseudo-console; ignored once it is closed.</summary>
    public void Resize(short columns, short rows)
    {
        lock (_lock)
        {
            if (_pseudoConsole.Value != 0)
                PInvoke.ResizePseudoConsole(_pseudoConsole, new COORD { X = columns, Y = rows });
        }
    }

    /// <summary>Kills every process in the job; the main process exits with <paramref name="exitCode"/>.</summary>
    public void TerminateJob(int exitCode)
    {
        // TerminateJobObject is thread-safe; the reference keeps the handle open against Dispose.
        var added = false;
        try
        {
            _job.DangerousAddRef(ref added);
            PInvoke.TerminateJobObject((HANDLE)_job.DangerousGetHandle(), unchecked((uint)exitCode));
        }
        catch (ObjectDisposedException)
        {
            // Disposed: the job is closed, and KILL_ON_JOB_CLOSE has killed everything in it.
        }
        finally
        {
            if (added)
                _job.DangerousRelease();
        }
    }

    /// <summary>Process ids currently in the job.</summary>
    public IReadOnlyList<int> JobProcessIds()
    {
        const int Max = 256;
        var size = sizeof(JOBOBJECT_BASIC_PROCESS_ID_LIST) + Max * sizeof(nuint);
        var memory = stackalloc byte[size];
        var list = (JOBOBJECT_BASIC_PROCESS_ID_LIST*)memory;
        list->NumberOfAssignedProcesses = Max;
        var added = false;
        try
        {
            _job.DangerousAddRef(ref added);
            if (!PInvoke.QueryInformationJobObject((HANDLE)_job.DangerousGetHandle(),
                    JOBOBJECTINFOCLASS.JobObjectBasicProcessIdList, list, (uint)size, null))
                return [];
        }
        catch (ObjectDisposedException)
        {
            return [];
        }
        finally
        {
            if (added)
                _job.DangerousRelease();
        }
        var ids = (nuint*)&list->ProcessIdList;
        var result = new int[list->NumberOfProcessIdsInList];
        for (var i = 0; i < result.Length; i++)
            result[i] = (int)ids[i];
        return result;
    }

    /// <summary>
    /// Closes the pseudo-console. Its conhost flushes the last output and exits, and
    /// <see cref="Output"/> then reaches EOF.
    /// </summary>
    public void ClosePseudoConsole()
    {
        HPCON pc;
        lock (_lock)
        {
            pc = _pseudoConsole;
            _pseudoConsole = default;
        }
        // Outside the lock: on older Windows builds this blocks until the output is drained.
        if (pc.Value != 0)
            PInvoke.ClosePseudoConsole(pc);
    }

    /// <summary>Kills the job (if anything is left in it) and releases every handle.</summary>
    public void Dispose()
    {
        ClosePseudoConsole();
        lock (_lock)
        {
            if (_disposed)
                return;
            _disposed = true;
            _input.Dispose();
            _job.Dispose(); // KILL_ON_JOB_CLOSE
            PInvoke.CloseHandle(_process);
        }
        Output.Dispose();
    }
}
